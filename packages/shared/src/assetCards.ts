import cards from "./assetCards.json";
import type { Vec3 } from "./map";

/** Upward-facing flat area of a model, in model units. */
export interface SupportSurface {
  y: number;
  area: number;
}

/** The axis a doorway opens onto, in the model's own frame. */
export type DoorFacing = "+x" | "-x" | "+z" | "-z";

/** A doorway at the foot of a facade, in model units: its centre, its width and where it opens. */
export interface AssetDoor {
  x: number;
  z: number;
  width: number;
  facing: DoorFacing;
}

/** Geometry facts read from one GLB, in the model's own units and root space. */
export interface AssetCard {
  model: string;
  size: Vec3;
  center: Vec3;
  minY: number;
  surfaces: SupportSurface[];
  /** Ground-level doorways; only on the City Kit buildings, the one kit whose doors can be read. */
  doors?: AssetDoor[];
}

/**
 * Machine-extracted cards keyed by model path, generated by `pnpm cards` from the GLB kits.
 * Covers every runtime model except avatars and weapons.
 */
export const ASSET_CARDS: Readonly<Record<string, AssetCard>> = cards as Record<string, AssetCard>;
